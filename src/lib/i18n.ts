export function translate(
  lang: Lang,
  key: string,
  fallback: string,
  overrides?: Record<string, string>,
): string {
  if (lang === 'en') return EN[key] ?? fallback
  const value = overrides?.[key]
  return value && value.trim() ? value : fallback
}
