import type { Product, ProductOption, ProductStatus, Specification } from '@/types'
import { productImage, type GlyphKind } from '@/lib/artwork'

/* ------------------------------ أدوات ------------------------------ */

export interface OptionSeed {
  label: string
  type: 'color' | 'storage' | 'size' | 'custom'
  values: Array<{ label: string; hex?: string; delta?: number; stock?: number }>
}

/** يبني خيار منتج مع معرّفات ثابتة */
function option(id: string, seed: OptionSeed): ProductOption {
  return {
    id,
    type: seed.type,
    label: seed.label,
    values: seed.values.map((value, index) => ({
      id: `${id}-${index + 1}`,
      label: value.label,
      hex: value.hex,
      priceDelta: value.delta ?? 0,
      stock: value.stock ?? 12,
      available: (value.stock ?? 12) > 0,
    })),
  }
}

function specs(pairs: Array<[string, string]>): Specification[] {
  return pairs.map(([key, value], index) => ({ id: `sp-${index + 1}`, key, value }))
}

export interface ProductSeed {
  id: string
  name: string
  sku: string
  brandId: string
  categoryIds: string[]
  price: number
  compareAtPrice?: number
  cost?: number
  stock: number
  sales: number
  glyph: GlyphKind
  seed: number
  short: string
  description: string
  tags: string[]
  options?: ProductOption[]
  specifications: Array<[string, string]>
  isNew?: boolean
  isBestSeller?: boolean
  isFeatured?: boolean
  createdDaysAgo: number
  lowStock?: number
  allowBackorder?: boolean
  status?: ProductStatus
}

const daysAgo = (days: number) => {
  const date = new Date()
  date.setDate(date.getDate() - days)
  return date.toISOString()
}

function build(seed: ProductSeed): Product {
  return {
    id: seed.id,
    name: seed.name,
    sku: seed.sku,
    shortDescription: seed.short,
    description: seed.description,
    images: [0, 1, 2].map((variant) => productImage(seed.glyph, seed.seed, variant)),
    price: seed.price,
    compareAtPrice: seed.compareAtPrice,
    cost: seed.cost ?? Math.round(seed.price * 0.72),
    stock: seed.stock,
    trackStock: true,
    lowStockThreshold: seed.lowStock ?? 5,
    allowBackorder: seed.allowBackorder ?? false,
    categoryIds: seed.categoryIds,
    brandId: seed.brandId,
    tags: seed.tags,
    options: seed.options ?? [],
    variants: [],
    specifications: specs(seed.specifications),
    relatedIds: [],
    isNew: seed.isNew ?? false,
    isBestSeller: seed.isBestSeller ?? false,
    isFeatured: seed.isFeatured ?? false,
    status: seed.status ?? 'published',
    rating: 0,
    reviewCount: 0,
    sales: seed.sales,
    weight: 1,
    dimensions: '—',
    createdAt: daysAgo(seed.createdDaysAgo),
  }
}

